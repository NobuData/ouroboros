-- ---------------------------------------------------------------------------
-- The 370 routed calls — everything the matrix's two numeric columns are made of.
--
-- One row per model call, which is the grain V010 chose and the grain both figures are
-- about. `task_kind` says which matrix row a call belongs to and `latency_ms` how long it
-- took (V020); `provider` and `model` are the connection and model its route's **primary**
-- hop resolves to, which is what a call that succeeded on its first hop records.
--
-- **The three sequences.** For a kind with `calls` rows, call `n` records
--
--   cost_cents = centre_cost    + (n − centre) × cost_step
--   latency_ms = centre_latency + (n − centre) × latency_step
--   tokens     = centre_tokens  + (n − centre) × token_step
--
-- with `centre = (calls + 1) / 2`. The offsets are symmetric, so each column's *mean* is its
-- centre — which makes `avg(cost_cents)` the `$/run avg` column exactly — and `calls` is odd,
-- so one row sits **at** the centre and `percentile_cont(0.5)` returns it rather than an
-- interpolation between two neighbours. Token totals are `calls × centre_tokens` for the same
-- reason, which is what makes the 31% share above land on a whole number.
--
-- Every centre is a multiple of five and every step divides it, so `tokens_in` and
-- `tokens_out` — four fifths and one fifth, as both earlier seeds split them — add back up to
-- the total with nothing lost to integer division.
--
-- **`cost_cents = 0` on the two local kinds, and it is not a null.** See the header: zero is
-- a price that was recorded, null is a price nobody recorded, and this workspace now holds
-- both so the difference is testable rather than asserted.
--
-- **The window** is #221's, for the reason its header gives: `occurred_at` is
-- `start + (today 00:00 − start) × n/(calls + 1)`, so every call lands strictly inside
-- `[start, today 00:00 UTC)` and none on either edge. `start` is the later of the month's
-- first instant and thirteen days ago — except on the first of a month, when *earlier this
-- month* is an empty range and the window is yesterday instead. On that one day the month
-- meters read the day's spend alone, exactly as they do without this file; the 30-day card
-- and the per-kind statistics are unaffected, because a window of thirteen days and a window
-- of one are both inside thirty.
-- ---------------------------------------------------------------------------
insert into ouroboros.token_usage
    (id, organization_id, run_id, provider, model, tokens_in, tokens_out,
     cost_cents, occurred_at, task_kind, latency_ms)
select ('5eed0014-0000-4000-8000-'
          || lpad((kind.id_base + call.n)::text, 12, '0'))::uuid,
       org."id", null, kind.provider, kind.model,
       measured.tokens / 5 * 4, measured.tokens / 5,
       kind.centre_cost + (call.n - kind.centre) * kind.cost_step,
       month_window.start_at
         + (utc.day_start - month_window.start_at)
           * (call.n::double precision / (kind.calls + 1)),
       kind.task_kind, measured.latency_ms
  from (values
         --  base  task kind     provider             model
         --                                  calls  centre  cost¢  step    p50ms  step   tokens  step
         (   0, 'analyze',    'anthropic',         'claude-sonnet-5',
             25,  13,   4.0000, 0.2500,  3100,  200,   50000,  2000),
         (  25, 'estimate',   'anthropic',         'claude-haiku-4-5',
             25,  13,   1.0000, 0.0500,  1200,   80,   14000,   500),
         (  50, 'plan',       'anthropic',         'claude-fable-5',
             15,   8,  31.0000, 3.0000,  9800,  900,  100000,  8000),
         (  65, 'implement',  'anthropic',         'claude-fable-5',
             15,   8,  87.0000, 9.0000, 41000, 3500,  260000, 20000),
         (  80, 'test-gen',   'copilot',           'gpt-5-codex',
             15,   8,  12.0000, 1.5000, 17400, 1800,  140000, 10000),
         (  95, 'review',     'anthropic',         'claude-fable-5',
             15,   8,  22.0000, 2.5000, 12600, 1200,  140000, 12000),
         ( 110, 'docs',       'ollama',            'qwen3-coder:32b',
             15,   8,   0.0000, 0.0000,  6300,  600,   40000,  3000),
         ( 125, 'commit-msg', 'openai_compatible', 'llama-4-maverick',
            245, 123,   0.0000, 0.0000,   800,    6,   80000,   500)
       ) as kind (id_base, task_kind, provider, model, calls, centre,
                  centre_cost, cost_step, centre_latency, latency_step,
                  centre_tokens, token_step)
  cross join lateral generate_series(1, kind.calls) as call (n)
  cross join lateral
       (select (kind.centre_tokens  + (call.n - kind.centre) * kind.token_step)::int,
               (kind.centre_latency + (call.n - kind.centre) * kind.latency_step)::int)
    as measured (tokens, latency_ms)
  join ouroboros.organization org on org."slug" = 'acme-robotics'
  cross join (select date_trunc('month', now() at time zone 'utc') at time zone 'utc',
                     date_trunc('day',   now() at time zone 'utc') at time zone 'utc')
          as utc (month_start, day_start)
  cross join lateral (select case
                              when utc.month_start < utc.day_start
                              then greatest(utc.month_start,
                                            utc.day_start - interval '13 days')
                              else utc.day_start - interval '1 day'
                            end)
          as month_window (start_at)
 where ${ouro_dev_seed}
on conflict do nothing;

