--
-- **Only `implement-primary` carries a cost cap**, because it is the only route the mockup
-- opens: its inspector reads *Max cost per run* `$2.50`, which is `max_cost_cents_per_run =
-- 250`. The other seven are null — *no cap configured* — rather than 250 repeated eight
-- times, because a policy nobody set is not a policy, and a seed that quietly applies one
-- everywhere would make the inspector's field look like a display of a default.
--
-- `allow_local_fallback` is on everywhere, which is the mockup's switch and V016's default;
-- `floor_hop_index` is null everywhere, which is *"Fail run instead of degrading below
-- fallback 2"* switched **off**. Null rather than a number is what off means here: a floor is
-- a hop index, and there is no index that means "no floor".
--
-- `updated_by` is Ken, the person who owns the workspace — these are routes somebody saved,
-- which is what the *Save routes* button writes.
-- ---------------------------------------------------------------------------
insert into ouroboros.routes
