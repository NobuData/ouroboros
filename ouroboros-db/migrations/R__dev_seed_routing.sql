  from (values
         (1, 'analyze',    'analyze-primary',    null),
         (2, 'estimate',   'estimate-primary',   null),
         (3, 'plan',       'plan-primary',       null),
         (4, 'implement',  'implement-primary',  250),
         (5, 'test-gen',   'testgen-primary',    null),
         (6, 'review',     'review-primary',     null),
         (7, 'docs',       'docs-primary',       null),
         (8, 'commit-msg', 'commitmsg-primary',  null)
