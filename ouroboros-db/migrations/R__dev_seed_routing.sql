--   | Health                       | `provider_connections.status` — #221's; CH.5 derives  |
--   | Used by                      | `alias_references` (V023) — computed, never stored    |
--   | Resolution chain (run #482)  | `resolution_snapshots` (V024) — one row               |
--
-- Nothing the registry *renders* is stored where it could be typed instead. No chip string,
-- no `degraded`, no `$15 · $75`, no `4 routes`: the chips are derived from `params` by CH.2
-- (#585), the health cell from the connection's status by CH.5 (#588), the price from the
-- catalog by CH.3 (#586), and the count from V023's view. tests/seed.test.sh asserts each of
-- those strings is absent from this file, and tests/seed.sql asserts what the derivations
-- have to work from.
--
-- ---------------------------------------------------------------------------
-- Decision M7, which is the whole reason this file is as long as it is.
-- ---------------------------------------------------------------------------
--
--   > `$/run`, p50 and spend are **computed** from `token_usage` + runs; no data → em-dash,
--   > never a fabricated number; local providers show `$0.00` only via real zero-price rows.
--
-- So `$0.87`, `41.0s`, `$412.80` and *"Local models served 31% of all tokens"* are **not**
-- seeded anywhere. There is no column on a route, an alias or a connection that any of them
-- could be written into, and this file writes none. What it seeds instead is the *usage*
-- those figures are aggregates of, arranged so the aggregation lands on the mockup.
--
-- That is a deliberately harder job than storing the answers, and it is the job because of
-- what storing them would cost: a `$/run` column filled by a seed leaves Z.5's aggregation
-- untested and M7's em-dash rule unverifiable. A number that was never computed cannot be
-- *absent* in the way the rule requires — the honest em-dash of a workspace with no data is
-- only observable if the populated workspace's figure was computed too.
--
-- **The arithmetic, in one table.** Each task kind is seeded a run of calls whose costs and
-- latencies are a symmetric arithmetic sequence around the mockup's figure — so the *mean*
-- of the costs is the `$/run avg` column exactly, and the *median* of the latencies is the
-- `p50 latency` column exactly, with no rounding anywhere:
--
--   | Task kind    | Calls | mean cost | `$/run avg` | median latency | `p50`  |
--   |--------------|------:|----------:|------------:|---------------:|-------:|
--   | `analyze`    |    25 |      4.00¢|       $0.04 |         3100ms |   3.1s |
--   | `estimate`   |    25 |      1.00¢|       $0.01 |         1200ms |   1.2s |
--   | `plan`       |    15 |     31.00¢|       $0.31 |         9800ms |   9.8s |
--   | `implement`  |    15 |     87.00¢|       $0.87 |        41000ms |  41.0s |
--   | `test-gen`   |    15 |     12.00¢|       $0.12 |        17400ms |  17.4s |
--   | `review`     |    15 |     22.00¢|       $0.22 |        12600ms |  12.6s |
--   | `docs`       |    15 |      0.00¢|       $0.00 |         6300ms |   6.3s |
--   | `commit-msg` |   245 |      0.00¢|       $0.00 |          800ms |   0.8s |
--
-- A symmetric sequence is what makes both exact at once. Offsets either side of the centre
-- cancel in a sum, so `avg(cost_cents)` is the centre; an odd number of calls puts one row
-- *at* the centre, so `percentile_cont(0.5)` is that row rather than an interpolation. The
-- spread is real variation — an `implement` call ranges 16.5s to 65.5s, and 24¢ to $1.50 —
-- which is what a median is worth having for.
--
-- ---------------------------------------------------------------------------
-- The four seeds share one ledger, and this one takes its spend out of #221's share.
-- ---------------------------------------------------------------------------
--
-- `token_usage` is one table and three of the four seeds write to it, so a row added here
-- moves a figure mockup 02 and mockup 07 already render. Two rules keep that from happening,
-- and both are asserted in tests/seed.sql:
--
--   1. **Nothing here lands on today.** Mockup 02's *Token spend · today* card is exactly
--      #68's twelve events; every row below is placed strictly before today's UTC midnight,
--      in the same window #221 uses and with the same first-of-the-month branch.
--
--   2. **The month meters do not move**, because #221 was reduced by exactly what this file
--      adds. Its header carries the arithmetic; the short form is that routed spend of
--      $22.25 (Anthropic) and $1.80 (Copilot) came out of that file's remainder rather than
--      on top of it, and 600 000 routed `docs` tokens came out of its Ollama share, so the
--      cards still read $412.80 / $64.10 / $76.00 and *2.1M tokens on-box*.
--
-- **What the 30-day card therefore reads, and where the mockup does not close.** Every row
-- any seed writes falls inside the trailing thirty days, so *Spend by provider · 30d* is the
-- calendar-month figure on every day of the month:
--
--   | Provider                | Seeded 30d | Mockup 06 | Mockup 07 (month) |
--   |-------------------------|-----------:|----------:|------------------:|
--   | Anthropic               |    $412.80 |   $412.80 |           $412.80 |
--   | GitHub Copilot          |     $76.00 |    $96.40 |            $76.00 |
--   | Cursor                  |     $64.10 |    $54.10 |            $64.10 |
--   | Local (vLLM + Ollama)   |      $0.00 |     $0.00 |             $0.00 |
--
-- The two disagreements are the mockups', not the seed's, and one of them is **not
-- reachable by any seed at all**: thirty days is a superset of month-to-date, so a 30-day
-- total can never be *less* than the month total inside it, and mockup 06 asks Cursor to be
-- $10.00 lower than mockup 07's card for the same rows. Copilot's $96.40 would need $20.40
-- dated before the month began — a window that is twenty-nine days wide on the 2nd and
-- **empty** on the 31st, which would make the card's figure depend on the date.
--
-- So this file seeds the reading both screens can hold at once, and states the discrepancy
-- here rather than leaving Z.5 (#198) to find it against a fixture that will not add up —
-- the same courtesy R__dev_seed_dashboard.sql pays where mockup 02's merge rate does not
-- close. Anthropic and the local `$0.00` land on the mockup exactly; Copilot and Cursor land
-- on mockup 07's, and #192's PR asks for the design to be amended to them.
--
-- ---------------------------------------------------------------------------
-- Zero-priced is not unpriced, and the difference is seeded in one workspace.
-- ---------------------------------------------------------------------------
--
-- `docs` and `commit-msg` route to local models, and their `$0.00` in the matrix — and the
-- local provider's `$0.00` on the spend card — is only honest if the calls were **priced,
-- and priced at nothing**. Their rows therefore carry `cost_cents = 0`, which is a recorded
-- fact about a call that cost nothing.
--
-- #68's and #221's Ollama rows carry `null` instead, which says the other thing: *nobody
-- priced this*. Both states now exist in `acme-robotics`, which is what makes DASH-J.4's
-- (#92) rule testable — a re-pricing pass must fill the nulls and leave the zeros alone, and
-- a stats service must render `$0.00` for one and `unpriced` for the other. Seeding only one
-- of the two would have left the distinction as a sentence in a header.
--
-- **The local token share is the same rule counted rather than summed.** *"Local models
-- served 31% of all tokens"* is `tokens on the two local kinds / all tokens` over the same
-- thirty days, and it lands on exactly 31% because the pieces were chosen to:
--
--   |                       | Cloud tokens | Local tokens |
--   |-----------------------|-------------:|-------------:|
--   | #68 — today           |    3 700 000 |      500 000 |
--   | #221 — earlier        |   33 400 000 |    1 000 000 |
--   | here — routed calls   |   11 200 000 |   20 200 000 |
--   | **Total**             | **48 300 000** | **21 700 000** |
--
-- 21 700 000 of 70 000 000 is 31.0%, with no rounding. The local half is large because that
-- is what the claim means: a workstation that answers every commit message and every docs
-- pass serves a third of the tokens and none of the bill.
--
-- ---------------------------------------------------------------------------
-- No `runs` row is written here, and that is decision M7 read carefully.
-- ---------------------------------------------------------------------------
--
-- A `runs` row is a **loop** — one issue, from *Implementing* to *Merged* — and mockup 02's
-- *Loops live*, *PRs merged · 7d* and *Avg. cycle time* are counts and averages over the
-- fifty-three #68 seeds. A routing call is a *step inside* a loop, and there are 370 of them
-- below; writing one run per call would change every figure on the dashboard.
--
-- V020 is what makes that unnecessary: `task_kind` and `latency_ms` live on the ledger row,
-- which is already one row per call, so the matrix's two columns are aggregates over rows
-- this file writes and the dashboard's are aggregates over rows #68 wrote. `run_id` is left
-- null throughout — these calls belong to a *kind of work*, and inventing a mapping from 370
-- synthetic calls onto 53 loops would be a fixture nothing renders.
--
-- ---------------------------------------------------------------------------
-- Ids, and the three properties every seed here has.
-- ---------------------------------------------------------------------------
--
-- Eight prefixes, on the convention R__dev_seed.sql set — an id beginning `5eed` came from a
-- seed, and the two hex digits after it say which table:
--
--   | Rows                        | Id                                                  |
--   |-----------------------------|-----------------------------------------------------|
--   | `model_aliases` (8)         | `5eed000f-0000-4000-8000-` + ordinal 1–8            |
--   | `task_kinds` (8)            | `5eed0010-0000-4000-8000-` + matrix position 1–8    |
--   | `routes` (8)                | `5eed0011-0000-4000-8000-` + its kind's position    |
--   | `route_hops` (17)           | `5eed0012-0000-4000-8000-` + ordinal 1–17           |
--   | `escalation_rules` (3)      | `5eed0013-0000-4000-8000-` + card position 1–3      |
--   | `token_usage` (370)         | `5eed0014-0000-4000-8000-` + ordinal 1–370          |
--   | `model_prices` (1)          | `5eed0016-0000-4000-8000-` + 1                      |
--   | `resolution_snapshots` (1)  | `5eed0017-0000-4000-8000-` + 1                      |
--
-- (`5eed0015` is R__dev_seed_audit.sql's, which sorts before this file and took it first.)
--
-- The usage ids are computed from a per-kind base and the call's number rather than written
-- out, for the reason #68 computes its seventy-seven: a list of 370 literals is a list nobody
-- proof-reads. They are as deterministic as literals are — the same file yields the same
-- uuid on every machine and every pass — which is the property the convention is for.
-- `gen_random_uuid()` appears nowhere, and tests/seed.test.sh asserts it.
--
-- It **cannot run in production** (every statement ends `and ${ouro_dev_seed}`, which is
-- `false` in flyway.toml), it is **idempotent** (every id is derived from literals and every
-- statement ends `on conflict do nothing`), and it **never fails on a database somebody has
-- edited** (children find their parents by natural key — the workspace by slug, a connection
-- by its kind and name, a kind by its name, an alias by its alias). Three statements name
-- their arbiter as `on conflict (id)`: `task_kinds`, `route_hops` and `escalation_rules` all
-- carry a **deferrable** unique key, and PostgreSQL refuses a targetless `on conflict` on
-- such a table outright — the same accommodation #68 makes for `queue_items`.
--
-- **The personal workspace is deliberately empty.** `kensuenobu` gets no alias, no task kind,
-- no route and no usage row, exactly as it gets no run and no provider — which is what makes
-- it the fixture AA.6 (#205) renders *"set up your first route"* against, and the one M7's
-- em-dashes can be observed in: a workspace with no usage has no `$/run` to average and no
-- latency to take a median of, and both must render `—` rather than `$0.00` and `0.0s`. It
-- gets no price override and no resolution snapshot either, so it is also the empty registry
-- CI.6 (#596) renders its guidance against.
--
-- ---------------------------------------------------------------------------
-- The eight aliases — the only place a raw model string is allowed to live.
--
-- Decision M1: routes name aliases, aliases name models, and `model_aliases.model_id` is the
-- one column in this schema where `claude-fable-5` may appear. Every hop below therefore
-- points at one of these rows, and swapping `coder-max` onto another model stays one edit of
-- one row.
--
-- Six are the matrix's. The seventh is `second-opinion`, which no route's chain contains and
-- the *security label* escalation rule names — Y.3 (#191) put that rule in the schema, so the
-- alias it adds a vote from has to exist here or the rule cannot be written at all. The
-- eighth is `gpt5-experiments`, mockup 21's **unbound** row (CG.4, #582; V019, decision R2):
-- a name created ahead of its key, bound to no connection, naming `gpt-5.2-preview`, and
-- `enabled = false` — which V019 requires of an unbound row rather than defaults, so the seed
-- says it. It is the registry's `✗ no key — connect a provider` fixture, and nothing routes
-- through it: its `0 routes` is a left join over `alias_references` that finds nothing.
--
-- **`params` and `restrictions` are mockup 21's chips, as structure** (V019, decision R3).
-- The registry draws `(max thinking)(400k budget)` beside `coder-max`, `(std thinking)`
-- beside `coder-std`, `(temp 0)(8k out)` beside `sizer`, `(ctx 32k)` beside `local-docs`,
-- `(batch ok)` beside `local-free` and `(review vote only)` beside `second-opinion`; none of
-- those strings is in this file. What is here is `{"thinking": "max", "token_budget":
-- 400000}` and its siblings, and CH.2 (#585) derives the chips — so the registry's parity
-- test passes only if the derivation works, which is the point of seeding structure rather
-- than text. `8192` and `32768` are stored as the powers of two the chips abbreviate, and
-- `400000` as the round thousand it is; CH.2 prints each in the unit it is a whole multiple
-- of. `coder-fallback` and `gpt5-experiments` carry nothing, which is the `—` cell: a
-- fixed-catalog model with nothing to tune, and a name with no provider to tune it for.
--
-- **`coder-max` carrying `thinking: max` does not make the effort ≥ L rule a no-op**, though
-- an earlier version of this header said it would. The rule's `params` are *policy* — Z.1
-- (#194) merges them over whatever the alias carries at resolution time, so the rule pins max
-- thinking for large work even after somebody edits the alias down to `std` — while the
-- alias's `params` are the registry's claim about how this name is called by default. In the
-- seeded workspace the two agree, and the merge is observably a merge rather than a swap: the
-- rule's document names `thinking` alone, and the resolved params still carry the alias's
-- `token_budget`.
--
-- Each bound alias finds its connection by natural key — the kind and display name #221
-- seeded — so no id from that file is repeated here. The unbound one has no connection to
-- find, and the `left join` plus the last `and` keep the two cases apart: a bound row whose
-- connection somebody has deleted is *skipped* rather than inserted as unbound, because V019
-- would refuse it enabled and take the whole migration down with it.
-- ---------------------------------------------------------------------------
insert into ouroboros.model_aliases
    (id, organization_id, alias, provider_connection_id, model_id, params,
     enabled, restrictions, updated_by)
select ('5eed000f-0000-4000-8000-' || lpad(seed.n::text, 12, '0'))::uuid,
       org."id", seed.alias, conn.id, seed.model_id, seed.params::jsonb,
       seed.enabled, seed.restrictions::jsonb, person."id"
  from (values
         (1, 'coder-max',        'anthropic',         'Anthropic Claude',
          'claude-fable-5',   '{"thinking": "max", "token_budget": 400000}', '{}', true),
         (2, 'coder-std',        'anthropic',         'Anthropic Claude',
          'claude-sonnet-5',  '{"thinking": "std"}',                         '{}', true),
         (3, 'sizer',            'anthropic',         'Anthropic Claude',
          'claude-haiku-4-5', '{"temperature": 0, "max_output": 8192}',      '{}', true),
         (4, 'coder-fallback',   'copilot',           'GitHub Copilot',
          'gpt-5-codex',      '{}',                                          '{}', true),
         (5, 'local-docs',       'ollama',            'Ollama · workstation',
          'qwen3-coder:32b',  '{"context_clamp": 32768}',                    '{}', true),
         (6, 'local-free',       'openai_compatible', 'OpenAI-compatible · local vLLM',
          'llama-4-maverick', '{}',                          '{"batch_ok": true}', true),
         (7, 'second-opinion',   'cursor',            'Cursor',
          'composer-2',       '{}',                   '{"review_vote_only": true}', true),
         (8, 'gpt5-experiments', null,                null,
          'gpt-5.2-preview',  '{}',                                          '{}', false)
       ) as seed (n, alias, kind, display_name, model_id, params, restrictions, enabled)
  join ouroboros.organization org on org."slug" = 'acme-robotics'
  join ouroboros."user" person on person."email" = 'ken@acme-robotics.dev'
  left join ouroboros.provider_connections conn
    on conn.organization_id = org."id"
   and conn.kind = seed.kind
   and conn.display_name = seed.display_name
 where ${ouro_dev_seed}
   and (seed.kind is null) = (conn.id is null)
on conflict do nothing;

-- ---------------------------------------------------------------------------
