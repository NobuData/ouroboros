/**
 * The embedded secrets ruleset — infrastructure option **3-A**, versioned in-repo.
 *
 * AP.3 ([#305](https://github.com/NobuData/ouroboros/issues/305)). A gitleaks-class set of
 * well-known credential formats plus keyword proximity — option 3-A budgets *roughly 150*, and
 * {@link SECRETS_RULESET_DISCLOSURE} counts what this version actually holds — run over the
 * *added* lines of a reported diff. It takes milliseconds, needs no external binary, and gives the same verdict
 * for the same diff every time — which is what lets a verdict be compared across re-evaluations.
 *
 * ---------------------------------------------------------------------------
 * **What it does not catch, said where the rules are.**
 *
 * A regex ruleset recognises a credential by its *shape*: a prefix (`AKIA`, `ghp_`, `xoxb-`), a
 * fixed length and alphabet, or a keyword sitting next to a value. A high-entropy secret with no
 * recognisable format — a random database password, an HMAC key someone generated by hand, a
 * token from a provider that is not listed here — has no shape to recognise. That is a recall
 * class of roughly **70 %**: this ruleset finds the common catastrophes (cloud keys, source-host
 * tokens, private key blocks) and misses the rest by construction.
 *
 * So a `secrets` pass means *"no known credential format was found in the added lines"* and
 * **never** *"this diff contains no secrets"*. {@link SECRETS_RULESET_DISCLOSURE} is that
 * sentence as data, for the Guardrails card's tooltip (#313), so a green tick never claims more
 * than the scan earned. Verified scanning — which does better and costs outbound calls carrying
 * candidate credentials — is AR.5 ([#319](https://github.com/NobuData/ouroboros/issues/319)).
 *
 * ---------------------------------------------------------------------------
 * **How a rule is shaped.**
 *
 *   * **`format` rules** carry their own evidence — a prefix or a structure that is the
 *     credential's signature. Their keywords are the literal prefix, used only as a cheap
 *     prefilter: a rule whose keyword is not in the text is never run.
 *   * **`near` rules** match a value with no signature of its own (32 hex characters, a UUID),
 *     which would fire on every checksum and id in a codebase. They count only when one of their
 *     keywords appears within {@link PROXIMITY_WINDOW} characters **before** the value on the same
 *     line — `DATADOG_API_KEY=…` fires, a bare hash in a lockfile does not. That is the keyword
 *     proximity the issue asks for, and it is where most of the false positives are cut.
 *   * **Generic rules** (`generic-password`, `generic-api-key`, the URI credentials) capture the
 *     value and discard obvious placeholders — `changeme`, `${PASSWORD}`, `<token>`, `xxxx` — and
 *     values with no digit in them, which is what a sentence or an identifier looks like.
 *
 * Every quantifier that is followed by more pattern is **bounded**, so no rule backtracks
 * quadratically on a long minified line.
 *
 * ---------------------------------------------------------------------------
 * **Versioning.** {@link SECRETS_RULESET_VERSION} is recorded on every `secrets` verdict
 * (`guardrail_evaluations.ruleset_version`), so *"the same diff under a newer ruleset"* is a
 * checkable explanation for a verdict that changed while the code did not. **Bump it with every
 * edit to {@link SECRET_RULES}** — adding, removing, or changing a pattern or a keyword.
 *
 * Rule ids are the evidence's `rule_id` and are held by V048 to
 * `^[a-z][a-z0-9]*(-[a-z0-9]+)*$`, at most 64 characters — the spec asserts every one does.
 */

/** The ruleset's version, as `ruleset_version` records it. `v3` is the card's *secrets ruleset v3*. */
export const SECRETS_RULESET_VERSION = "v3";

/**
 * How far before a `near` rule's value its keyword may sit, in characters on the same line.
 *
 * Wide enough for `export DATADOG_API_KEY = "` and `datadog: { api_key: '`, narrow enough that a
 * keyword at the start of a long line does not vouch for a hash at its end.
 */
export const PROXIMITY_WINDOW = 64;

/** One rule of the ruleset. */
export interface SecretRule {
  /** The evidence's `rule_id` — lower-case, hyphenated, at most 64 characters. */
  readonly id: string;
  /** What it finds, for a person reading the ruleset. Never rendered with a match. */
  readonly description: string;
  /** The pattern. Always global, so a line with two credentials reports the first and moves on. */
  readonly pattern: RegExp;
  /**
   * Lower-case literals, at least one of which must appear in the text for the rule to run.
   *
   * For a `format` rule they are the prefilter; for a `near` rule they are also the proximity
   * anchor.
   */
  readonly keywords: readonly string[];
  /** Whether a keyword must sit within {@link PROXIMITY_WINDOW} characters before the match. */
  readonly proximity: boolean;
  /**
   * Which capture group holds the value, for rules that screen out placeholders.
   *
   * Absent for rules whose whole match is a signature — nobody writes `AKIA` + sixteen
   * base-32 characters as a placeholder.
   */
  readonly valueGroup?: number;
}

/**
 * A rule whose match is its own signature.
 *
 * @param id - The rule id.
 * @param description - What it finds.
 * @param source - The pattern's source. Case-sensitive: formats are.
 * @param keywords - Lower-case literals the text must contain for the rule to run.
 * @returns The rule.
 */
function format(
  id: string,
  description: string,
  source: string,
  keywords: readonly string[],
): SecretRule {
  return { id, description, pattern: new RegExp(source, "g"), keywords, proximity: false };
}

/**
 * A rule whose value has no signature, and so needs a keyword beside it.
 *
 * The value is wrapped in alphanumeric look-arounds, so `[a-f0-9]{32}` matches a 32-character
 * hex token and not 32 characters out of the middle of a 64-character one.
 *
 * @param id - The rule id.
 * @param description - What it finds.
 * @param keywords - Lower-case literals, one of which must precede the value within
 *   {@link PROXIMITY_WINDOW} characters.
 * @param value - The value's pattern source.
 * @returns The rule.
 */
function near(
  id: string,
  description: string,
  keywords: readonly string[],
  value: string,
): SecretRule {
  return {
    id,
    description,
    pattern: new RegExp(`(?<![A-Za-z0-9])(?:${value})(?![A-Za-z0-9])`, "g"),
    keywords,
    proximity: true,
  };
}

/** A UUID, which several providers use as a bare API key. */
const UUID = "[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}";

