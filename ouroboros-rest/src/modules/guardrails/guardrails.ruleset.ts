/**
 * Build a generic `keyword = "value"` rule.
 *
 * @param id - The rule id.
 * @param description - What it finds.
 * @param words - The keywords, lower-case, matched case-insensitively.
 * @returns The rule, capturing the quoted value as group 1.
 */
function assignment(id: string, description: string, words: readonly string[]): SecretRule {
  const alternation = words.map((word) => word.replace(/[-_]/g, "[-_]?")).join("|");

  return {
    id,
    description,
    pattern: new RegExp(
      `(?:${alternation})[A-Za-z0-9_-]{0,20}["']?\\s{0,5}(?:[:=]|:=|=>)\\s{0,5}["'\`]([^"'\`\\s]{8,200})["'\`]`,
      "gi",
    ),
    keywords: words,
    proximity: false,
    valueGroup: 1,
  };
}

/**
 * Build a credentials-in-a-URI rule — `scheme://user:password@host`.
 *
 * @param id - The rule id.
 * @param description - What it finds.
 * @param schemes - The scheme alternation's source.
 * @param keywords - Lower-case scheme literals for the prefilter.
 * @returns The rule, capturing the password as group 1.
 */
function uriCredential(
  id: string,
  description: string,
  schemes: string,
  keywords: readonly string[],
): SecretRule {
  return {
    id,
    description,
    pattern: new RegExp(`\\b(?:${schemes})://[^\\s:/@]{1,256}:([^\\s/@]{3,256})@`, "gi"),
    keywords,
    proximity: false,
    valueGroup: 1,
  };
}

