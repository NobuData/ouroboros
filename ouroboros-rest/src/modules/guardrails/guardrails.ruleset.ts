/**
 * Values the generic rules treat as placeholders rather than secrets.
 *
 * Anchored and whole: `changeme` is a placeholder and `changeme7Qx…` is not.
 */
const PLACEHOLDER =
  /^(?:\$\{[^}]*\}|\$\([^)]*\)|\{\{[^}]*\}\}|<[^>]*>|%[A-Za-z_]+%|\$[A-Za-z_][A-Za-z0-9_]*|x+|\*+|\.+|-+|(?:your|my|the|some)[-_]?[a-z_-]*|changeme|change[-_]me|password\d*|passwd|secret|example|sample|dummy|placeholder|redacted|test(?:ing)?\d*|fake|todo|null|none|undefined)$/i;

/**
 * Is a captured value a real candidate, or a placeholder / an identifier?
 *
 * @param value - What a generic rule captured.
 * @returns `true` when the value is worth reporting: not a known placeholder, and containing at
 *   least one digit and one letter — a secret that is all letters is a word, and one that is all
 *   digits is a number, and both are far more often code than credentials.
 */
export function isCandidateValue(value: string): boolean {
  return !PLACEHOLDER.test(value) && /[0-9]/.test(value) && /[A-Za-z]/.test(value);
}
