_log = logging.getLogger(__name__)

#: The only refs a run may push: its own branch, under this prefix.
RUN_BRANCH_PREFIX: Final = "ouro/run-"

#: A run branch name, as the control plane builds it.
RUN_BRANCH_PATTERN: Final = re.compile(r"^ouro/run-[A-Za-z0-9_-]+$")

#: The longest issue title a subject line carries before it is cut.
SUBJECT_TITLE_LIMIT: Final = 72

#: What the message body says about how the change was made.
GENERATED_STATEMENT: Final = (
    "Generated by an automated Ouroboros loop for run {run}; "
    "a person reviews it before it merges."
)

#: The status a dulwich error names, when it names one.
_STATUS = re.compile(r"\b(4\d\d|5\d\d)\b")


class PublishError(RuntimeError):
    """The run branch was not published. The message is one sentence a person can act on.

    Attributes:
        reason: The sentence.
        code: The control plane's refusal code, when it refused; ``None`` for the host or
            this engine.
    """

    def __init__(self, reason: str, code: str | None = None) -> None:
        """Record why.

        Args:
            reason: The sentence.
            code: The refusal code, if the control plane refused.
        """
        super().__init__(reason)
        self.reason = reason
        self.code = code


class PushFailedError(RuntimeError):
    """The host refused the push or could not be reached — no credential in the message."""


@dataclass(frozen=True)
class CommitIdentity:
    """The configured identity every attributed commit is authored and committed by.

    Attributes:
        name: ``OURO_ENGINE_COMMIT_AUTHOR_NAME``.
        email: ``OURO_ENGINE_COMMIT_AUTHOR_EMAIL``.
    """

    name: str
    email: str

    def as_git(self) -> bytes:
        """The identity as git writes it.

        Returns:
            ``Name <email>``.
        """
        return f"{self.name} <{self.email}>".encode()


@dataclass(frozen=True)
class PublishRun:
    """What the commit messages say about the run.

    Attributes:
        run_id: ``runs.id``.
        issue_number: The issue.
        issue_title: Its title.
        branch: The run branch, as ``start`` answered it.
        workflow_tag: The pinned workflow's slug.
        workflow_version: Its pinned version.
        default_alias: The model a checkpoint names when its stage pins none — the run's.
        aliases: The routing alias per model stage.
        started_by: Who started the run — the co-author — or ``None``.
    """

    run_id: str
    issue_number: int
    issue_title: str
    branch: str
    workflow_tag: str
    workflow_version: int
    default_alias: str
    aliases: Mapping[str, str]
    started_by: StartedBy | None


@dataclass(frozen=True)
class Published:
    """A successful publish.

    Attributes:
        head: The attributed commit now at the branch's tip on the host.
        commits: How many attributed commits this push added.
    """

    head: str
    commits: int


def commit_message(run: PublishRun, checkpoint: CheckpointCommit) -> str:
    """One attributed commit's message: subject, statement, trailers.

    Args:
        run: The run.
        checkpoint: The checkpoint it is made from.

    Returns:
        The message, ending in a newline.
    """
    title = " ".join(run.issue_title.split())
    if len(title) > SUBJECT_TITLE_LIMIT:
        title = title[: SUBJECT_TITLE_LIMIT - 1].rstrip() + "…"
    stage = checkpoint.stage
    if checkpoint.attempt is not None:
        stage = f"{stage} attempt {checkpoint.attempt}"
    trailers = [
        f"Ouroboros-Run: {run.run_id}",
        f"Ouroboros-Workflow: {run.workflow_tag}@v{run.workflow_version}",
        f"Ouroboros-Model: {run.aliases.get(checkpoint.stage, run.default_alias)}",
        f"Ouroboros-Stage: {stage}",
    ]
    if run.started_by is not None:
        trailers.append(
            f"Co-authored-by: {run.started_by.name} <{run.started_by.email}>"
        )
    return (
        f"{checkpoint.stage}: {title} (#{run.issue_number})\n\n"
        f"{GENERATED_STATEMENT.format(run=run.run_id)}\n\n" + "\n".join(trailers) + "\n"
    )


def attribute(
    workspace: RunWorkspace,
    run: PublishRun,
    identity: CommitIdentity,
    checkpoints: list[CheckpointCommit],
) -> list[tuple[Commit, CheckpointCommit]]:
    """Write one attributed commit per checkpoint, chained on the last one pushed.

    Each carries its checkpoint's tree and time, so the same checkpoints always produce the
    same commits. Nothing moves a branch: the commits are objects until a push names one.

    Args:
        workspace: The run's tree.
        run: The run.
        identity: The author and committer.
        checkpoints: Oldest first.

    Returns:
        ``(commit, the checkpoint it was made from)``, oldest first.
    """
    parent = (workspace.published() or workspace.spec.base_commit).encode("ascii")
    made: list[tuple[Commit, CheckpointCommit]] = []
    for checkpoint in checkpoints:
        commit = Commit()
        commit.tree = checkpoint.tree
        commit.parents = [parent]
        commit.author = commit.committer = identity.as_git()
        commit.author_time = commit.commit_time = checkpoint.time
        commit.author_timezone = commit.commit_timezone = checkpoint.timezone
        commit.encoding = b"UTF-8"
        commit.message = commit_message(run, checkpoint).encode("utf-8")
        workspace.git.object_store.add_object(commit)
        made.append((commit, checkpoint))
        parent = commit.id
    return made


def check_refspec(refspec: str, branch: str) -> bytes:
    """Hold the control plane's refspec to the one shape this engine pushes.

    Refused before any network call: more than one ref, a ``+`` (force), either side outside
    ``refs/heads/ouro/run-``, or a branch other than the run's.

    Args:
        refspec: The grant's refspec.
        branch: The run branch.

    Returns:
        The remote ref to update.

    Raises:
        PublishError: The refspec is not exactly the run branch, unforced.
    """
    parts = refspec.split()
    if len(parts) != 1:
        raise PublishError("The push names more than one ref; a run pushes one branch.")
    spec = parts[0]
    if spec.startswith("+"):
        raise PublishError(
            "The push asks to force; a run branch is never force-pushed."
        )
    source, colon, target = spec.partition(":")
    expected = f"refs/heads/{branch}"
    if not colon or not RUN_BRANCH_PATTERN.match(branch):
        raise PublishError(f"The push is not to a run branch: {spec!r}.")
    if source != expected or target != expected:
        raise PublishError(f"The push names {spec!r}, not the run's branch {branch!r}.")
    return target.encode("ascii")


class PushClient(Protocol):
    """The one call a push needs from a git transport."""

    def send_pack(
        self,
        path: bytes,
        update_refs: Callable[[dict[Ref, ObjectID]], dict[Ref, ObjectID]],
        generate_pack_data: Any,
    ) -> Any:
        """Advertise the remote refs, ask which to update, and send the pack.

        Args:
            path: The repository path on the host.
            update_refs: Decides the update from the remote's refs.
            generate_pack_data: Produces the objects to send.

        Returns:
            dulwich's ``SendPackResult``.
        """
        ...


class PushTransport(Protocol):
    """Opens a git transport to a remote, credential in hand. Tests count its calls."""

    def connect(
        self, remote: str, username: str, password: str
    ) -> tuple[PushClient, bytes]:
        """Open the transport — the push's first network step.

        Args:
            remote: The repository URL.
            username: The credential's user name.
            password: The credential.

        Returns:
            The client and the repository path on the host.

        Raises:
            PushFailedError: The remote is not one this engine pushes to.
        """
        ...


class DulwichPushTransport:
    """dulwich's smart-HTTP client, in process: no subprocess, no config, no URL credential."""

    def __init__(
        self, *, timeout_seconds: float = 60.0, allow_local: bool = False
    ) -> None:
        """Configure it.

        Args:
            timeout_seconds: The socket timeout of one push.
            allow_local: Accept an existing local repository path — for tests only, like
                :class:`~ouroboros_engine.code.clones.CloneStore`'s.
        """
        self._timeout = timeout_seconds
        self._allow_local = allow_local

    def connect(
        self, remote: str, username: str, password: str
    ) -> tuple[PushClient, bytes]:
        """Open the transport. ``https://`` only, and never with credentials in the URL.

        Args:
            remote: The repository URL.
            username: The credential's user name.
            password: The credential.

        Returns:
            The client and the repository path.

        Raises:
            PushFailedError: The remote is not ``https://host/owner/name`` (or, with
                ``allow_local``, an existing local path).
        """
        if remote.startswith("https://"):
            parts = urlsplit(remote)
            if parts.username or parts.password or not parts.hostname:
                raise PushFailedError("the remote must be https://host/owner/name")
            client: GitClient = HttpGitClient(
                f"https://{parts.netloc}",
                username=username,
                password=password,
                timeout=self._timeout,
                quiet=True,
            )
            return client, parts.path.encode()
        if self._allow_local and Path(remote).is_dir():
            client, path = get_transport_and_path(remote, quiet=True)
            return client, path.encode()
        raise PushFailedError("the remote must be https://host/owner/name")


def push_ref(
    workspace: RunWorkspace,
    transport: PushTransport,
    grant: PushGrant,
    target: bytes,
    head: bytes,
) -> None:
    """Push one ref, fast-forward only.

    Args:
        workspace: The run's tree, which holds every object to send.
        transport: Opens the connection.
        grant: The remote and this push's credential.
        target: The remote ref — already checked.
        head: The commit it is to point at.

    Raises:
        PushFailedError: The host refused, diverged, or could not be reached — a reason that
            never carries the credential.
    """
    repo = workspace.git
    secret = grant.secret()

    def update_refs(refs: dict[Ref, ObjectID]) -> dict[Ref, ObjectID]:
        current = refs.get(Ref(target))
        if current is not None and current != head:
            try:
                fast_forward = can_fast_forward(repo, current, head)
            except KeyError:
                fast_forward = False
            if not fast_forward:
                raise PushFailedError(
                    "the run branch on the host has commits this run did not make; "
                    "a run branch is never force-pushed"
                )
        return {Ref(target): ObjectID(head)}

    def generate_pack_data(
        have: Set[ObjectID],
        want: Set[ObjectID],
        *,
        ofs_delta: bool = False,
        progress: Callable[..., None] | None = None,
    ) -> tuple[int, Iterator[UnpackedObject]]:
        known = {sha for sha in have if sha in repo.object_store}
        return repo.generate_pack_data(
            known, set(want), progress=progress, ofs_delta=ofs_delta
        )

    try:
        client, path = transport.connect(grant.remote, grant.username, secret)
        result = client.send_pack(path, update_refs, generate_pack_data)
    except PushFailedError:
        raise
    except SendPackError as refused:
        raise PushFailedError(
            f"the host refused the push: {_clean(refused, secret)}"
        ) from None
    except (HangupException, GitProtocolError, OSError) as broken:
        raise PushFailedError(_host_reason(broken, secret)) from None
    for ref, error in (getattr(result, "ref_status", None) or {}).items():
        if error is not None:
            name = ref.decode("utf-8", "replace")
            raise PushFailedError(f"the host refused {name}: {_clean(error, secret)}")


def _clean(value: object, secret: str) -> str:
    """A host message as one line, with the credential removed should a host echo it.

    Args:
        value: The message or error.
        secret: The credential.

    Returns:
        The line, at most 300 characters.
    """
    text = value.decode("utf-8", "replace") if isinstance(value, bytes) else str(value)
    if secret:
        text = text.replace(secret, "***")
    return " ".join(text.split())[:300] or "no detail"


def _host_reason(error: BaseException, secret: str) -> str:
    """The host's reason for a transport failure, by its HTTP status when it names one.

    Args:
        error: What dulwich raised.
        secret: The credential, kept out of the reason.

    Returns:
        A clause.
    """
    found = _STATUS.search(str(error))
    status = int(found.group(1)) if found else None
    if status in (401, 403):
        return f"the host refused the credential (HTTP {status})"
    if status == 404:
        return "the host has no such repository (HTTP 404)"
    if status is not None:
        return f"the host answered HTTP {status}: {_clean(error, secret)}"
    return f"the host could not be reached: {_clean(error, secret)}"


class Publisher:
    """Turns a run's unpublished checkpoints into one fast-forward push of its branch."""

    def __init__(self, identity: CommitIdentity, transport: PushTransport) -> None:
        """Hold the identity and the transport.

        Args:
            identity: ``OURO_ENGINE_COMMIT_AUTHOR_NAME`` / ``…_EMAIL``.
            transport: Opens the push's connection.
        """
        self._identity = identity
        self._transport = transport

    async def publish(
        self, workspace: RunWorkspace, run: PublishRun, reporter: RunReporter
    ) -> Published | None:
        """Publish whatever the run has checkpointed since its last push.

        Args:
            workspace: The run's tree, at its last checkpoint.
            run: The run.
            reporter: The epoch-fenced writes.

        Returns:
            What was pushed, or ``None`` when there was nothing new.

        Raises:
            PublishError: Refused here or by ``ouroboros-rest``, or the host failed. The tree
                and its checkpoints are left as they were.
        """
        checkpoints = await asyncio.to_thread(workspace.unpublished_checkpoints)
        if not checkpoints:
            return None
        made = await asyncio.to_thread(
            attribute, workspace, run, self._identity, checkpoints
        )
        head = made[-1][0].id

        files = await asyncio.to_thread(workspace.changes)
        change_set = await reporter.files(files)
        try:
            grant = await reporter.push(
                run.branch, head.decode("ascii"), change_set.change_set_seq
            )
        except ControlPlaneError as refused:
            raise PublishError(
                f"ouroboros-rest refused the push ({refused.code}): {refused}",
                refused.code,
            ) from None
        target = check_refspec(grant.refspec, run.branch)

        try:
            await asyncio.to_thread(
                push_ref, workspace, self._transport, grant, target, head
            )
        except PushFailedError as failed:
            reason = f"The push of {run.branch} failed: {failed}."
            _log.warning("run %s: %s", run.run_id, reason)
            await reporter.push_result(run.branch, "failed", reason=reason)
            raise PublishError(reason) from None

        await reporter.commits(
            [
                IngestCommit(
                    sha=commit.id.decode("ascii"),
                    message=commit.message.decode("utf-8", "replace")[:8192],
                    committed_at=_iso(checkpoint),
                )
                for commit, checkpoint in made
            ]
        )
        await reporter.push_result(
            run.branch, "pushed", pushed_sha=head.decode("ascii")
        )
        await asyncio.to_thread(
            workspace.mark_published, head.decode("ascii"), made[-1][1].sha
        )
        _log.info(
            "run %s: pushed %d commit(s) to %s", run.run_id, len(made), run.branch
        )
        return Published(head=head.decode("ascii"), commits=len(made))


def _iso(checkpoint: CheckpointCommit) -> str:
    """A checkpoint's commit time, ISO 8601 in UTC.

    Args:
        checkpoint: The checkpoint.

    Returns:
        ``YYYY-MM-DDTHH:MM:SSZ``.
    """
    return datetime.fromtimestamp(checkpoint.time, UTC).strftime("%Y-%m-%dT%H:%M:%SZ")
