"""The branch publisher — a run's checkpoints, as attributed commits, on one pushed branch.

DI.2 (`#1310 <https://github.com/NobuData/ouroboros/issues/1310>`_). DI.1's working tree
commits a local checkpoint at every stage boundary, under a placeholder identity and on a
branch no remote knows. This is the first moment Ouroboros writes into a customer's
repository, so it is narrow by construction::

    unpublished checkpoints ─▶ attributed commits (one per checkpoint, same tree)
        ─▶ change-set reported (guardrails judge exactly the pushed tree)
        ─▶ POST /internal/runs/{id}/push          ouroboros-rest refuses, or grants:
                                                  refspec + remote + one-call credential
        ─▶ refspec checked here                   one ref, no ``+``, the run branch only
        ─▶ git push (in process, fast-forward)    the credential in memory, nowhere else
        ─▶ commits reported (AP.1) + POST …/push/result (the audit row)

**Honest authorship.** Each attributed commit carries the tree of one checkpoint — one
stage attempt — and is authored *and* committed by the configured Ouroboros identity
(``OURO_ENGINE_COMMIT_AUTHOR_NAME`` / ``…_EMAIL``). The message names the issue and the run,
says an automated loop generated it, and ends with trailers::

    Ouroboros-Run: <run id>
    Ouroboros-Workflow: <tag>@v<version>
    Ouroboros-Model: <alias>
    Ouroboros-Stage: <stage> attempt <n>
    Co-authored-by: <the person who started the run> <their address>

A commit is not signed and carries no App identity (#374): it says who and what produced it,
and no more. The same checkpoint always produces the same commit — same tree, parent,
identity, times and message — so a publish retried after a failed push writes nothing new.

**One ref, fast-forward only.** The refspec is the control plane's, and it is checked here
before anything touches the network: exactly one ref, no ``+``, both sides the run branch
under ``refs/heads/ouro/run-``. The push itself refuses a remote tip that is not an ancestor
of the new one, and never deletes. A second publish after a correction round therefore adds
commits on top of the first.

**The credential.** It arrives in the grant as a :class:`~pydantic.SecretStr`, is handed to
the git transport as constructor arguments, and is dropped with it. There is no subprocess, so
it is never in an argument list or an environment; the tree's ``.git/config`` names no remote;
and no log line or reason carries it.

**Failure leaves the tree.** A refusal or a host error raises :class:`PublishError` with one
sentence a person can act on; the caller finishes the run ``failed`` and keeps the tree, so the
next attempt publishes the same checkpoints.
"""

from __future__ import annotations

